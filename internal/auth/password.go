package auth

import (
	"crypto/rand"
	"crypto/subtle"
	"encoding/base64"
	"errors"
	"fmt"
	"strings"

	"golang.org/x/crypto/argon2"
)

const (
	saltBytes = 16
	keyBytes  = 32
	memoryKiB = 19 * 1024
	passes    = 2
	threads   = 1
)

func HashPassword(password string) (string, error) {
	if len(password) < 12 || len(password) > 128 {
		return "", errors.New("пароль должен содержать от 12 до 128 байт")
	}
	salt := make([]byte, saltBytes)
	if _, err := rand.Read(salt); err != nil {
		return "", err
	}
	key := argon2.IDKey([]byte(password), salt, passes, memoryKiB, threads, keyBytes)
	return fmt.Sprintf("$argon2id$v=19$m=19456,t=2,p=1$%s$%s",
		base64.RawStdEncoding.EncodeToString(salt),
		base64.RawStdEncoding.EncodeToString(key)), nil
}

// CheckPassword accepts the Argon2id format generated by this app and the
// previous learning project. Malformed hashes are rejected before hashing.
func CheckPassword(password, encoded string) (bool, error) {
	parts := strings.Split(encoded, "$")
	if len(parts) != 6 || parts[0] != "" || parts[1] != "argon2id" ||
		parts[2] != "v=19" || parts[3] != "m=19456,t=2,p=1" {
		return false, errors.New("неподдерживаемый формат хеша")
	}
	salt, err := base64.RawStdEncoding.DecodeString(parts[4])
	if err != nil {
		return false, err
	}
	expected, err := base64.RawStdEncoding.DecodeString(parts[5])
	if err != nil {
		return false, err
	}
	if len(salt) != saltBytes || len(expected) != keyBytes {
		return false, errors.New("неверная длина соли или хеша")
	}
	actual := argon2.IDKey([]byte(password), salt, passes, memoryKiB, threads, keyBytes)
	return subtle.ConstantTimeCompare(actual, expected) == 1, nil
}
